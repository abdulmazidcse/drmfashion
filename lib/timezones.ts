/** The zone a given shipping destination's local time should be read in. */
export function resolveOrderTimezone(
  countryCode?: string | null,
  stateCode?: string | null
): string {
  const country = (countryCode || "").toUpperCase()
  const state = (stateCode || "").toUpperCase()

  if (country === "US" && TIMEZONE_BY_US_STATE[state]) return TIMEZONE_BY_US_STATE[state]
  if (country === "CA" && TIMEZONE_BY_CA_PROVINCE[state]) return TIMEZONE_BY_CA_PROVINCE[state]
  return TIMEZONE_BY_COUNTRY[country] || "UTC"
}

/**
 * An order's placed-at date and time, in the customer's own timezone, with
 * the zone abbreviation appended (e.g. "Sep 23, 2026, 7:14 PM EDT") so it's
 * unambiguous which "local" time is being shown.
 */
export function formatOrderDateTime(
  date: Date | string,
  countryCode?: string | null,
  stateCode?: string | null
): string {
  const d = typeof date === "string" ? new Date(date) : date
  const timeZone = resolveOrderTimezone(countryCode, stateCode)
  return new Intl.DateTimeFormat("en-US", {
    timeZone,
    dateStyle: "medium",
    timeStyle: "short",
    timeZoneName: "short",
  }).format(d)
}
