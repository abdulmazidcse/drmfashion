// ─── Order date/time localisation ────────────────────────────────────────────
// The order-confirmation email and both invoice views used to render
// "when this order was placed" in whatever timezone happened to be rendering
// it — the visitor's browser for a customer-facing page, the server's clock
// for the email — so the same order showed a different hour depending on who
// was looking at it, with no indication either way of which zone it was.
//
// This resolves one fixed zone per order, from the shipping destination
// already stored on it (`Order.shippingCountry` / `shippingState`, see
// lib/orderCreation.ts), so "when was this placed" reads the same everywhere
// and is labelled with its own zone abbreviation instead of being ambiguous.
//
// One representative zone per country is a deliberate simplification for
// countries spanning several (Russia, Brazil, Indonesia, Australia, etc.) —
// a receipt doesn't need to be more precise than "the customer's country."
// The exception is the US and Canada, which get state/province-level zones:
// `lib/regions.ts` already collects a state/province code for both, this
// store's orders skew heavily US/Canada, and those two are exactly the
// countries where "just use the country" gets the hour visibly wrong.

